#!/usr/bin/env node
/** Run the pinned release verifier from a fresh local clone of the exact commit.
 * No remote Git authentication, deployment or PayPal credentials are required. */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { lstatSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cleanEnvironment, releaseCommandInvocation } from './release-candidate-verify.mjs';

const sourceRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA = 'rightsreceipt-clean-release-checkout-v1';
const SHAREABLE_SCHEMA = 'rightsreceipt-clean-release-handoff-v1';
const SHA = /^[0-9a-f]{40}$/u;
const HASH = /^[0-9a-f]{64}$/u;
const PUBLIC_GIT_IDENTITY = ['nolankido', '212063387+nolankido@users.noreply.github.com',
  'nolankido', '212063387+nolankido@users.noreply.github.com'].join('\t');
const MAX_RELEASE_LOG_BYTES = 16 * 1024 * 1024;
// Only fixed failure identifiers generated by the canonical verifier may
// cross from its private evidence record into the outer JSON summary.
const SAFE_RELEASE_FAILURES = new Set([
  'not_repository_root', 'commit_unavailable', 'checkout_not_clean',
  'tracked_source_git_unavailable', 'tracked_source_index_invalid',
  'tracked_source_entry_unsupported', 'tracked_source_tree_mismatch',
  'tracked_source_hidden_index_flag', 'tracked_source_worktree_mismatch',
  'tracked_source_unavailable', 'local_environment_override_present',
  'package_manager_config_check_unavailable', 'local_package_manager_override_present',
  'package_json_unavailable', 'unsupported_node', 'package_manager_not_pinned',
  'lockfile_missing', 'lockfile_not_committed', 'lockfile_differs_from_head',
  'release_stage_1_timed_out', 'release_stage_2_timed_out',
  'release_stage_3_timed_out', 'release_stage_4_timed_out',
  'verification_changed_checkout', 'verification_changed_source',
  'judge_rehearsal_evidence_invalid',
]);
const SAFE_HANDOFF_ERRORS = new Set([
  'node_22_required', 'source_not_repository', 'source_not_repository_root',
  'source_commit_unavailable', 'git_unavailable', 'private_output_unavailable',
  'checkout_unavailable', 'checkout_identity_mismatch', 'release_result_invalid',
  'release_verification_failed', 'public_export_failed', 'public_export_result_invalid',
  'clean_release_failed',
]);

class CleanReleaseError extends Error {
  constructor(code) { super('Clean release checkout did not complete.'); this.code = code; }
}

export function requireCleanReleaseNode(version = process.versions.node) {
  const match = /^(\d+)\.(\d+)\.\d+$/u.exec(version);
  if (!match || Number(match[1]) !== 22 || Number(match[2]) < 13) {
    throw new CleanReleaseError('node_22_required');
  }
}

function run(executable, args, cwd, timeout = 120000, environment = process.env) {
  return spawnSync(executable, args, {
    cwd, encoding: 'utf8', windowsHide: true, timeout, maxBuffer: 16 * 1024 * 1024,
    // A synchronous parent must not wait indefinitely for a child that
    // catches SIGTERM without exiting after the outer release deadline.
    killSignal: 'SIGKILL',
    env: { ...environment, GIT_TERMINAL_PROMPT: '0', GIT_LFS_SKIP_SMUDGE: '1' },
  });
}

function git(cwd, args, code = 'git_unavailable') {
  const result = run('git', args, cwd);
  if (result.error || result.status !== 0) throw new CleanReleaseError(code);
  return result.stdout.trim();
}

function ownedDirectory(path) {
  try {
    mkdirSync(path, { recursive: true, mode: 0o700 });
    const stat = lstatSync(path);
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error('not_owned_directory');
  } catch { throw new CleanReleaseError('private_output_unavailable'); }
}

/** Clone committed content only; leave all original working files untouched. */
export function createCleanReleaseCheckout(source, privateRoot) {
  const root = resolve(source);
  const top = git(root, ['rev-parse', '--show-toplevel'], 'source_not_repository');
  try {
    if (realpathSync(top) !== realpathSync(root)) throw new Error('not_root');
  } catch { throw new CleanReleaseError('source_not_repository_root'); }
  const commit = git(root, ['rev-parse', '--verify', 'HEAD'], 'source_commit_unavailable');
  if (!SHA.test(commit)) throw new CleanReleaseError('source_commit_unavailable');

  const privateBase = resolve(privateRoot);
  ownedDirectory(privateBase);
  const checkouts = join(privateBase, 'checkouts');
  ownedDirectory(checkouts);
  const checkout = mkdtempSync(join(checkouts, 'candidate-'));
  const cloned = run('git', ['clone', '--quiet', '--no-hardlinks', '--', root, checkout], root);
  if (cloned.error || cloned.status !== 0) throw new CleanReleaseError('checkout_unavailable');
  git(checkout, ['checkout', '--quiet', '--detach', commit], 'checkout_unavailable');
  if (git(checkout, ['rev-parse', '--verify', 'HEAD']) !== commit
    || git(root, ['rev-parse', '--verify', 'HEAD']) !== commit
    || git(checkout, ['status', '--porcelain=v1', '--untracked-files=all']) !== '') {
    throw new CleanReleaseError('checkout_identity_mismatch');
  }
  return Object.freeze({ commit, checkout, privateBase });
}

/** Surface actionable release failure codes without exposing private logs. */
function sanitizedReleaseDiagnostics(record) {
  const entries = Array.isArray(record?.preflightFailures) ? record.preflightFailures : [];
  const safeCodes = entries.filter(code => typeof code === 'string' && SAFE_RELEASE_FAILURES.has(code));
  const commands = Array.isArray(record?.commands) ? record.commands.slice(0, 4) : [];
  const firstFailure = commands.findIndex(command =>
    Number.isInteger(command?.exitCode) && command.exitCode !== 0);
  return Object.freeze({
    failureCodes: Object.freeze([...new Set(safeCodes)].slice(0, 32)),
    unknownFailureCodesPresent: safeCodes.length !== entries.length,
    firstFailedStage: firstFailure < 0 ? null : firstFailure + 1,
  });
}

/** A fixed, path-free response suitable for copying into a support conversation.
 * The full validated evidence and export locations remain in private local output. */
export function shareableReleaseSummary(outcome, { exportRequested = false } = {}) {
  const passed = outcome?.status === 'passed';
  const releasePassed = passed || outcome?.releaseStatus === 'passed';
  const code = passed ? null : SAFE_HANDOFF_ERRORS.has(outcome?.code)
    ? outcome.code : 'clean_release_failed';
  const input = outcome?.diagnostics;
  let diagnostics;
  if (input && typeof input === 'object' && !Array.isArray(input)) {
    const original = Array.isArray(input.failureCodes) ? input.failureCodes : [];
    const filtered = original.filter(value => typeof value === 'string'
      && SAFE_RELEASE_FAILURES.has(value));
    diagnostics = Object.freeze({
      failureCodes: Object.freeze([...new Set(filtered)].slice(0, 32)),
      unknownFailureCodesPresent: input.unknownFailureCodesPresent === true
        || original.length !== filtered.length,
      firstFailedStage: [1, 2, 3, 4].includes(input.firstFailedStage)
        ? input.firstFailedStage : null,
    });
  }
  return Object.freeze({
    schemaVersion: SHAREABLE_SCHEMA,
    status: passed ? 'passed' : 'failed',
    code,
    releaseStatus: releasePassed ? 'passed' : 'not_verified',
    publicExportStatus: !exportRequested ? 'not_requested'
      : outcome?.publicExport?.status === 'passed' ? 'passed' : 'not_verified',
    ...(diagnostics ? { diagnostics } : {}),
    limitation: 'Path-free local result only. This does not prove PayPal settlement, public GitHub or YouTube availability, or Devpost submission.',
  });
}

/** Keep actionable private paths after a single shareable run, including a
 * successful export. Never write into the audited release evidence directory. */
function savePrivateHandoff(outcome, privateBase) {
  const evidencePath = outcome?.evidencePath;
  const checkout = outcome?.checkoutPath;
  if (outcome?.schemaVersion !== SCHEMA || typeof evidencePath !== 'string'
    || typeof checkout !== 'string' || !isAbsolute(evidencePath) || !isAbsolute(checkout)
    || !SHA.test(outcome.commit ?? '') || basename(evidencePath) !== 'verification.json') return false;
  const evidenceRoot = resolve(privateBase, 'evidence');
  const runDirectory = dirname(evidencePath);
  const runName = basename(runDirectory);
  if (!withinDirectory(evidenceRoot, runDirectory)
    || !/^run-[A-Za-z0-9_-]{1,100}$/u.test(runName)) return false;
  try {
    const rootStat = lstatSync(evidenceRoot), runStat = lstatSync(runDirectory);
    const fileStat = lstatSync(evidencePath);
    if (!rootStat.isDirectory() || rootStat.isSymbolicLink()
      || !runStat.isDirectory() || runStat.isSymbolicLink()
      || !fileStat.isFile() || fileStat.isSymbolicLink()
      || !withinDirectory(realpathSync(evidenceRoot), realpathSync(runDirectory))) return false;
    const outputRoot = join(privateBase, 'handoffs');
    ownedDirectory(outputRoot);
    writeFileSync(join(outputRoot, `${runName}.json`), JSON.stringify(outcome, null, 2) + '\n',
      { flag: 'wx', mode: 0o600 });
    return true;
  } catch { return false; }
}

/** Shareable stdout stays path-free while a unique private file retains the
 * exact export and checkout locations without requiring another full run. */
export function prepareCleanReleaseOutput(outcome, {
  shareableRequested = false, exportRequested = false, privateBase = '',
} = {}) {
  if (!shareableRequested) return outcome;
  const shared = shareableReleaseSummary(outcome, { exportRequested });
  if (typeof outcome?.evidencePath !== 'string') return shared;
  return Object.freeze({ ...shared, privateHandoffSaved: savePrivateHandoff(outcome, privateBase) });
}

/** Hash the original, bounded, regular stage log from the validated evidence run.
 * A digest-shaped field alone is insufficient to prove a stage saved output. */
function matchingReleaseLog(evidencePath, index, executable, stream, expectedHash) {
  const stem = String(index + 1).padStart(2, '0') + '-'
    + executable.replace(/[^A-Za-z0-9._-]/gu, '_');
  const path = join(dirname(evidencePath), `${stem}.${stream}.log`);
  try {
    const stat = lstatSync(path);
    if (!stat.isFile() || stat.isSymbolicLink() || stat.size > MAX_RELEASE_LOG_BYTES) {
      return false;
    }
    return createHash('sha256').update(readFileSync(path)).digest('hex') === expectedHash;
  } catch { return false; }
}

/** A claimed pass must account for the complete, exact four-stage release.
 * The inner verifier remains authoritative; this guards against a truncated
 * or unrelated passing JSON record being accepted by its outer wrapper. */
function completePassingReleaseRecord(record, checkout, evidencePath) {
  if (typeof checkout !== 'string' || !isAbsolute(checkout)
    || record.node !== process.versions.node || record.packageManager !== 'pnpm@12.8.2'
    || !Array.isArray(record.preflightFailures) || record.preflightFailures.length !== 0
    || record.judgeEvidence?.root !== 'judge'
    || !Array.isArray(record.commands) || record.commands.length !== 4) return false;
  const releaseStages = [
    [process.execPath, [join(checkout, 'scripts', 'public-release-audit.mjs'), '--snapshot-only']],
    ['corepack', ['pnpm', 'install', '--frozen-lockfile']],
    ['corepack', ['pnpm', 'verify']],
    [process.execPath, [join(checkout, 'scripts', 'judge-rehearsal.mjs'),
      '--output', join(dirname(evidencePath), 'judge')]],
  ];
  const expected = releaseStages.map(([executable, args]) => {
    const invocation = releaseCommandInvocation(executable, args);
    return [invocation.executable, ...invocation.args];
  });
  return record.commands.every((entry, index) => entry && typeof entry === 'object'
    && !Array.isArray(entry) && Array.isArray(entry.command)
    && entry.command.length === expected[index].length
    && entry.command.every((arg, position) => arg === expected[index][position])
    && entry.exitCode === 0 && entry.signal === null && entry.spawnError === null
    && Number.isSafeInteger(entry.durationMs) && entry.durationMs >= 0
    && HASH.test(entry.stdoutSha256 ?? '') && HASH.test(entry.stderrSha256 ?? '')
    && matchingReleaseLog(evidencePath, index, entry.command[0], 'stdout', entry.stdoutSha256)
    && matchingReleaseLog(evidencePath, index, entry.command[0], 'stderr', entry.stderrSha256));
}

/** The existing release verifier is still the sole authority for passing. */
export function validateCleanReleaseResult({ result, commit, privateBase, checkout }) {
  let summary;
  try { summary = JSON.parse(result?.stdout ?? ''); }
  catch { throw new CleanReleaseError('release_result_invalid'); }
  if (!summary || typeof summary !== 'object' || Array.isArray(summary)) {
    throw new CleanReleaseError('release_result_invalid');
  }
  const evidencePath = typeof summary.evidencePath === 'string' ? resolve(summary.evidencePath) : '';
  const evidenceRoot = resolve(privateBase, 'evidence');
  const relativePath = relative(evidenceRoot, evidencePath);
  if (!relativePath || relativePath.startsWith('..') || relativePath.startsWith(sep)
    || !isAbsolute(summary.evidencePath ?? '') || relativePath.split(sep).length !== 2
    || basename(evidencePath) !== 'verification.json' || !SHA.test(commit)
    || summary.schemaVersion !== 'rightsreceipt-release-candidate-v1'
    || summary.mode !== 'full' || summary.commit !== commit) {
    throw new CleanReleaseError('release_result_invalid');
  }
  let record;
  try {
    const runDirectory = dirname(evidencePath);
    const rootStat = lstatSync(evidenceRoot), runStat = lstatSync(runDirectory);
    const fileStat = lstatSync(evidencePath);
    const actualRoot = realpathSync(evidenceRoot), actualRun = realpathSync(runDirectory);
    const actualFile = realpathSync(evidencePath);
    if (!rootStat.isDirectory() || rootStat.isSymbolicLink()
      || !runStat.isDirectory() || runStat.isSymbolicLink()
      || !fileStat.isFile() || fileStat.isSymbolicLink()
      || fileStat.size < 1 || fileStat.size > 512 * 1024
      || !withinDirectory(actualRoot, actualRun)
      || dirname(actualFile) !== actualRun || basename(actualFile) !== 'verification.json') {
      throw new Error('invalid_evidence_path');
    }
    record = JSON.parse(readFileSync(evidencePath, 'utf8'));
  }
  catch { throw new CleanReleaseError('release_result_invalid'); }
  if (!record || typeof record !== 'object' || Array.isArray(record)) {
    throw new CleanReleaseError('release_result_invalid');
  }
  // Never diagnose a failed run using unrelated or stale evidence. The
  // verifier's commit/mode binding applies to both passes and failures.
  if (record.schemaVersion !== summary.schemaVersion || record.commit !== commit
    || record.mode !== 'full') throw new CleanReleaseError('release_result_invalid');
  if (record.status === 'passed'
    && !completePassingReleaseRecord(record, checkout, evidencePath)) {
    throw new CleanReleaseError('release_result_invalid');
  }
  const passed = result.status === 0 && summary.status === 'passed'
    && record.status === 'passed';
  return Object.freeze({ status: passed ? 'passed' : 'failed',
    code: passed ? null : 'release_verification_failed', commit, evidencePath,
    ...(passed ? {} : { diagnostics: sanitizedReleaseDiagnostics(record) }) });
}

function withinDirectory(base, target) {
  const path = relative(base, target);
  return path !== '' && path !== '..' && !path.startsWith('..' + sep) && !isAbsolute(path);
}

/** Confirm the optional export really corresponds to the passing release and source tree. */
export function validateCleanPublicExportResult({ result, commit, checkout, privateBase, evidencePath }) {
  if (result?.error || result?.status !== 0) throw new CleanReleaseError('public_export_failed');
  let summary, manifest;
  try { summary = JSON.parse(result.stdout); }
  catch { throw new CleanReleaseError('public_export_result_invalid'); }
  const exportsRoot = join(privateBase, 'exports');
  const repositoryPath = typeof summary.repositoryPath === 'string' ? resolve(summary.repositoryPath) : '';
  const manifestPath = typeof summary.manifestPath === 'string' ? resolve(summary.manifestPath) : '';
  if (summary.schemaVersion !== 'rightsreceipt-public-export-v1' || summary.status !== 'passed'
    || summary.sourceCommit !== commit || !SHA.test(summary.publicCommit ?? '')
    || !SHA.test(summary.tree ?? '') || !withinDirectory(exportsRoot, repositoryPath)
    || !withinDirectory(exportsRoot, manifestPath) || basename(repositoryPath) !== 'repo'
    || basename(manifestPath) !== 'manifest.json'
    || dirname(repositoryPath) !== dirname(manifestPath)) {
    throw new CleanReleaseError('public_export_result_invalid');
  }
  try {
    const actualExportsRoot = realpathSync(exportsRoot);
    if (!withinDirectory(actualExportsRoot, realpathSync(repositoryPath))
      || !withinDirectory(actualExportsRoot, realpathSync(manifestPath))
      || !lstatSync(manifestPath).isFile() || lstatSync(manifestPath).isSymbolicLink()) throw new Error();
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  } catch { throw new CleanReleaseError('public_export_result_invalid'); }
  let sourceTree, publicTree, publicCommit, commitCount, publicStatus, remotes, refs, author;
  try {
    sourceTree = git(checkout, ['rev-parse', 'HEAD^{tree}']);
    publicTree = git(repositoryPath, ['rev-parse', 'HEAD^{tree}']);
    publicCommit = git(repositoryPath, ['rev-parse', 'HEAD']);
    commitCount = git(repositoryPath, ['rev-list', '--count', 'HEAD']);
    publicStatus = git(repositoryPath, ['status', '--porcelain=v1', '--untracked-files=all']);
    remotes = git(repositoryPath, ['remote']);
    refs = git(repositoryPath, ['for-each-ref', '--format=%(refname)']);
    author = git(repositoryPath, ['log', '-1', '--format=%an%x09%ae%x09%cn%x09%ce']);
  } catch { throw new CleanReleaseError('public_export_result_invalid'); }
  const releaseHash = createHash('sha256').update(readFileSync(evidencePath)).digest('hex');
  if (manifest.schemaVersion !== summary.schemaVersion || manifest.status !== 'passed'
    || manifest.sourceCommit !== commit || manifest.sourceTree !== sourceTree
    || manifest.publicCommit !== publicCommit || manifest.publicTree !== publicTree
    || manifest.exactTreeMatch !== true || manifest.repositoryDirectory !== 'repo'
    || manifest.releaseVerificationSha256 !== releaseHash
    || !HASH.test(manifest.sourceSnapshotAuditSha256 ?? '')
    || !HASH.test(manifest.publicHistoryAuditSha256 ?? '')
    || manifest.publicJudgeExperience?.status !== 'passed'
    || manifest.publicJudgeExperience?.mode !== 'offline'
    || manifest.publicJudgeExperience?.scenarioCount !== 3
    || manifest.publicJudgeExperience?.resetCount !== 3
    || manifest.publicJudgeExperience?.externalRequests !== 0
    || manifest.publicJudgeExperience?.paymentEvidence !== 'simulated_only'
    || manifest.publicJudgeExperience?.aiModelExecution !== 'real_local_inference'
    || manifest.publicJudgeExperience?.aiSyntheticRequestCount !== 2
    || manifest.publicJudgeExperience?.aiRightsFieldComparisons !== 24
    || manifest.publicJudgeExperience?.aiContradictionWarningVisible !== true
    || !HASH.test(manifest.publicJudgeExperience?.aiModelArtifactSha256 ?? '')
    || manifest.publicAuthorName !== 'nolankido'
    || manifest.publicAuthorEmail !== '212063387+nolankido@users.noreply.github.com'
    || summary.publicCommit !== publicCommit || summary.tree !== publicTree
    || publicCommit === commit || sourceTree !== publicTree || commitCount !== '1'
    || publicStatus !== '' || remotes !== '' || refs !== 'refs/heads/main'
    || author !== PUBLIC_GIT_IDENTITY) {
    throw new CleanReleaseError('public_export_result_invalid');
  }
  return Object.freeze({ status: 'passed', publicCommit, publicTree, repositoryPath, manifestPath });
}

export function main(args = process.argv.slice(2)) {
  if (args.length === 1 && args[0] === '--help') {
    process.stdout.write('Usage: node scripts/clean-release-checkout.mjs [--export-public] [--shareable]\nRequires Node 22.13+. Creates an ignored local clone and runs the complete pinned release verification. Optional export creates a sanitized private one-commit repository, never a GitHub remote. --shareable omits paths and commit identifiers from JSON output and saves a detailed private result in .data/clean-release/handoffs/ when release evidence exists.\n');
    return 0;
  }
  const options = new Set(args);
  const exportRequested = options.has('--export-public');
  const shareableRequested = options.has('--shareable');
  if (options.size !== args.length || [...options].some(arg =>
    arg !== '--export-public' && arg !== '--shareable')) {
    process.stdout.write(JSON.stringify({ schemaVersion: SCHEMA, status: 'failed', code: 'invalid_arguments' }) + '\n');
    return 2;
  }
  const privateBase = join(sourceRoot, '.data', 'clean-release');
  const output = outcome => process.stdout.write(JSON.stringify(prepareCleanReleaseOutput(outcome,
    { shareableRequested, exportRequested, privateBase })) + '\n');
  try {
    requireCleanReleaseNode();
    ownedDirectory(join(sourceRoot, '.data'));
    const { checkout, commit } = createCleanReleaseCheckout(sourceRoot, privateBase);
    const evidenceRoot = join(privateBase, 'evidence');
    ownedDirectory(evidenceRoot);
    const result = run(process.execPath,
      [join(checkout, 'scripts', 'release-candidate-verify.mjs'), '--output', evidenceRoot],
      checkout, 30 * 60 * 1000, cleanEnvironment());
    const outcome = validateCleanReleaseResult({ result, commit, privateBase, checkout });
    if (exportRequested && outcome.status === 'passed') {
      const exportRoot = join(privateBase, 'exports');
      ownedDirectory(exportRoot);
      const exportResult = run(process.execPath,
        [join(checkout, 'scripts', 'export-public-release.mjs'), '--release-evidence',
          outcome.evidencePath, '--output', exportRoot, '--verify-judge'],
        checkout, 15 * 60 * 1000, cleanEnvironment());
      try {
        const publicExport = validateCleanPublicExportResult({
          result: exportResult, commit, checkout, privateBase, evidencePath: outcome.evidencePath,
        });
        output({ schemaVersion: SCHEMA, ...outcome,
          checkoutPath: checkout, publicExport });
        return 0;
      } catch (error) {
        const code = error instanceof CleanReleaseError ? error.code : 'public_export_failed';
        output({ schemaVersion: SCHEMA, status: 'failed', code,
          releaseStatus: 'passed', commit, evidencePath: outcome.evidencePath,
          checkoutPath: checkout });
        return 1;
      }
    }
    output({ schemaVersion: SCHEMA, ...outcome, checkoutPath: checkout });
    return outcome.status === 'passed' ? 0 : 1;
  } catch (error) {
    const code = error instanceof CleanReleaseError ? error.code : 'clean_release_failed';
    output({ schemaVersion: SCHEMA, status: 'failed', code });
    return 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main();
}
