import type {
  BuyerClarificationResponse, CreatorClarificationResponse,
} from "@rightsreceipt/contracts";
import { RoleBanner, ScaffoldNotice, SurfaceCard } from "@rightsreceipt/ui";
import { useEffect, useState } from "react";
import { NavLink, useParams } from "react-router-dom";
import { loadBuyerClarification, loadCreatorClarification } from "./api";
import "./clarification.css";

type LoadingState<T> =
  | { readonly status: "loading" }
  | { readonly status: "loaded"; readonly data: T }
  | { readonly status: "error"; readonly error: string };

function ClarificationFields({plan}: {
  plan: CreatorClarificationResponse["plan"];
}) {
  return (
    <>
      {plan.unsupported.length ? (
        <SurfaceCard eyebrow="Unsupported rights" title="Scope requires creator review">
          <p>The following requested rights cannot be silently changed into supported permissions.</p>
          <ul className="rr-clarification-list">
            {plan.unsupported.map(item => (
              <li key={item.fieldName}>
                <strong>{item.label}:</strong> {item.explanation}
              </li>
            ))}
          </ul>
        </SurfaceCard>
      ) : null}
      {plan.questions.length ? (
        <section aria-labelledby="clarification-questions-title">
          <h2 id="clarification-questions-title">Details requiring clarification</h2>
          <ol className="rr-clarification-list">
            {plan.questions.map(item => (
              <li key={item.fieldName}>
                <strong>{item.label}:</strong> {item.question}
                <span className="rr-clarification-reason">{item.reason.replaceAll("_", " ")}</span>
                {item.evidenceSpans.length ? (
                  <ul className="rr-clarification-evidence">
                    {item.evidenceSpans.map(span => (
                      <li key={`${span.startUtf16}:${span.endUtf16}`}>
                        Buyer evidence: <q>{span.text}</q>
                      </li>
                    ))}
                  </ul>
                ) : null}
              </li>
            ))}
          </ol>
        </section>
      ) : (
        <SurfaceCard eyebrow="No clarification questions" title="No missing or conflicting fields found">
          <p>{plan.source === "human_corrected"
            ? "The saved human rights review is complete. Any quote must still be generated by the deterministic pricing service."
            : "The extracted fields contain no missing or conflicting details. A creator must still independently confirm the terms."}</p>
        </SurfaceCard>
      )}
      <ScaffoldNotice>
        These are question drafts, not an automatic license, quote, buyer response, or payment confirmation.
        Unsupported rights remain blocked. The learned model cannot approve a field.
      </ScaffoldNotice>
    </>
  );
}

export function CreatorClarificationPage() {
  const { caseId = "" } = useParams();
  const [refresh, setRefresh] = useState(0);
  const [state, setState] = useState<LoadingState<CreatorClarificationResponse>>({status: "loading"});
  const [copyStatus, setCopyStatus] = useState("");
  useEffect(() => {
    let active = true;
    // Refreshing a case invalidates prior async data and resets the loading state.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setState({status:"loading"});
    setCopyStatus("");
    loadCreatorClarification(caseId).then(data => {
      if(active) setState({status:"loaded",data});
    }).catch((error:unknown) => {
      if(active) setState({status:"error",error:error instanceof Error?error.message:"Unable to load clarifications."});
    });
    return () => {active = false;};
  }, [caseId,refresh]);
  async function copyQuestions(plan: CreatorClarificationResponse["plan"]) {
    const plain = plan.questions.map((entry,i)=>`${i+1}. ${entry.question}`).join("\n\n");
    try {
      await navigator.clipboard.writeText(plain);
      setCopyStatus("Question drafts copied. Answers are not recorded automatically.");
    } catch {setCopyStatus("Clipboard unavailable. Select and copy the questions manually.");}
  }
  return (
    <>
      <RoleBanner role="Creator clarification" nextAction="Review missing and conflicting fields" />
      <div className="rr-clarification-shell">
        <h1>Clarification plan</h1>
        <p>Questions use fixed wording and are based on source evidence or saved human corrections, never unverified model guesses.</p>
        {state.status === "loading" ? <p role="status">Checking material rights fields.</p> : null}
        {state.status === "error" ? (
          <div className="rr-error-panel" role="alert">
            <p>{state.error}</p>
            <button type="button" className="rr-button rr-button-secondary" onClick={()=>setRefresh(n=>n+1)}>Try again</button>
          </div>
        ):null}
        {state.status === "loaded" ? (
          <>
            <p className="rr-clarification-summary">
              {state.data.plan.questions.length} question drafts, {state.data.plan.unsupported.length} unsupported rights, {state.data.plan.resolvedFieldCount} resolved fields.
              Source: {state.data.plan.source.replaceAll("_"," ")}.
            </p>
            <ClarificationFields plan={state.data.plan} />
            {state.data.plan.questions.length ? (
              <button type="button" className="rr-button rr-button-primary" onClick={()=>copyQuestions(state.data.plan)}>
                Copy clarification questions
              </button>
            ) : null}
            {copyStatus ? <p role="status">{copyStatus}</p> : null}
            <div className="rr-actions">
              <NavLink className="rr-button rr-button-secondary" to={`/creator/cases/${caseId}`}>Return to human rights review</NavLink>
              <NavLink className="rr-button rr-button-secondary" to={`/creator/cases/${caseId}/extraction`}>Source evidence</NavLink>
            </div>
          </>
        ) : null}
      </div>
    </>
  );
}

/** Capability-scoped read-only question page. No answers or approvals are accepted here. */
export function BuyerClarificationPage() {
  const { capability = "" } = useParams();
  const [state, setState] = useState<LoadingState<BuyerClarificationResponse>>({status:"loading"});
  useEffect(() => {
    let active = true;
    // A changed capability must clear stale buyer questions before reloading.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setState({status:"loading"});
    loadBuyerClarification(capability).then(data => {if(active)setState({status:"loaded",data});})
      .catch((error:unknown)=>{if(active)setState({status:"error",error:error instanceof Error?error.message:"Clarification link is unavailable."});});
    return () => {active=false;};
  },[capability]);
  return (
    <>
      <RoleBanner role="Buyer clarification" nextAction="Review requested licensing details" />
      <div className="rr-clarification-shell">
        <h1>Clarification questions</h1>
        <p>This page is limited to your asset-specific request. It does not accept or send your answers.</p>
        {state.status==="loading"?<p role="status">Loading questions.</p>:null}
        {state.status==="error"?<p role="alert" className="rr-error-panel">{state.error}</p>:null}
        {state.status==="loaded" ? (
          <>
            <p>Image: <strong>{state.data.assetTitle}</strong>, by {state.data.creatorDisplayName}.</p>
            <ClarificationFields plan={state.data.plan} />
            <p>Please discuss any answers with the creator. No answers have been stored or sent through this page.</p>
            <NavLink className="rr-button rr-button-secondary" to={`/request/${capability}`}>
              Back to buyer request
            </NavLink>
          </>
        ):null}
      </div>
    </>
  );
}
